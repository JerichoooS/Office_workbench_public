-- ---------- 0. 清理 v1 旧表（线上无真实数据，已与用户确认） ----------
DROP TABLE IF EXISTS module_records CASCADE;

DROP TABLE IF EXISTS import_batches CASCADE;

DROP TABLE IF EXISTS ai_outputs CASCADE;

DROP TABLE IF EXISTS modules CASCADE;

DROP TABLE IF EXISTS llm_settings CASCADE;

-- 防误跑（2026-10-22 补）：todos 表里已经有数据 = 正在使用的库，拒绝执行，避免把全部待办删掉。
-- 只在全新库上执行 001；之后的改动都在 002 以后的文件里。
DO $$
DECLARE has_rows boolean := false;
BEGIN
  IF to_regclass('public.todos') IS NOT NULL THEN
    EXECUTE 'SELECT EXISTS (SELECT 1 FROM public.todos LIMIT 1)' INTO has_rows;
  END IF;
  IF has_rows THEN
    RAISE EXCEPTION 'todos 表里已有数据：001 只能在全新的库上执行，已拒绝（数据没有动）';
  END IF;
  DROP TABLE IF EXISTS todos CASCADE;
END $$;

-- ---------- 1. 通用：updated_at 自动维护 ----------
CREATE OR REPLACE FUNCTION wb_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := now(); RETURN NEW; END $$;

-- ---------- 2. 用户设置（每人一行） ----------
CREATE TABLE user_settings (
  owner_id        text PRIMARY KEY DEFAULT auth.uid(),
  morning_on      boolean NOT NULL DEFAULT true,
  morning_time    time    NOT NULL DEFAULT '08:30',
  evening_on      boolean NOT NULL DEFAULT true,
  evening_time    time    NOT NULL DEFAULT '18:00',
  default_reminder text   NOT NULL DEFAULT 'before_60',      -- none | before_15 | before_60 | before_1440
  ai_enabled      boolean NOT NULL DEFAULT false,
  llm_api_key     text,
  llm_base_url    text    NOT NULL DEFAULT 'https://api.deepseek.com',
  llm_model       text    NOT NULL DEFAULT 'deepseek-chat',
  theme           text    NOT NULL DEFAULT 'linen',
  timezone        text    NOT NULL DEFAULT 'Asia/Shanghai',
  last_morning_sent date,
  last_evening_sent date,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

-- ---------- 3. 联系对象：人 / 部门 / 科室 / 单位 ----------
CREATE TABLE contacts (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id   text NOT NULL DEFAULT auth.uid(),
  name       text NOT NULL,
  kind       text NOT NULL DEFAULT 'person' CHECK (kind IN ('person','department','section','unit')),
  org        text,                                   -- 所属单位/部门，如「某公司 · 采购部」
  phone      text,
  note       text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ---------- 4. 任务（大）：有起止时间的一件事 ----------
CREATE TABLE tasks (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id       text NOT NULL DEFAULT auth.uid(),
  title          text NOT NULL,
  description    text,
  start_date     date,
  end_date       date,
  status         text NOT NULL DEFAULT 'in_progress' CHECK (status IN ('not_started','in_progress','done')),
  archived_at    timestamptz,                        -- 非空 = 已归档；置空 = 恢复
  source_task_id bigint REFERENCES tasks(id) ON DELETE SET NULL,  -- 套用自哪个历史任务
  tags           text[] NOT NULL DEFAULT '{}',
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE task_contacts (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id   text NOT NULL DEFAULT auth.uid(),
  task_id    bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  contact_id bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  role       text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (task_id, contact_id)
);

-- ---------- 5. 待办（小） ----------
CREATE TABLE todos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id      text NOT NULL DEFAULT auth.uid(),
  task_id       bigint REFERENCES tasks(id) ON DELETE SET NULL,
  title         text NOT NULL,
  notes         text,
  status        text NOT NULL DEFAULT 'todo' CHECK (status IN ('todo','doing','waiting','done')),
  priority      smallint CHECK (priority BETWEEN 0 AND 3),   -- 0=P0 最高；NULL=未设置
  due_at        timestamptz,
  due_all_day   boolean NOT NULL DEFAULT true,               -- true=只有日期没有具体时刻
  waiting_on    bigint REFERENCES contacts(id) ON DELETE SET NULL,
  waiting_since timestamptz,
  repeat_rule   jsonb,                                       -- {"freq":"daily"} | {"freq":"weekly","days":[1,3]} | {"freq":"monthly","day":15}
  checklist     jsonb NOT NULL DEFAULT '[]',                 -- [{"text":"…","done":false}]
  tags          text[] NOT NULL DEFAULT '{}',
  sort_order    double precision NOT NULL DEFAULT 0,
  completed_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX todos_owner_status_due ON todos (owner_id, status, due_at);

CREATE INDEX todos_task ON todos (task_id);

CREATE TABLE todo_logs (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id   text NOT NULL DEFAULT auth.uid(),
  todo_id    bigint NOT NULL REFERENCES todos(id) ON DELETE CASCADE,
  content    text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------- 6. 提醒 ----------
CREATE TABLE reminders (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id       text NOT NULL DEFAULT auth.uid(),
  todo_id        bigint NOT NULL REFERENCES todos(id) ON DELETE CASCADE,
  kind           text NOT NULL CHECK (kind IN ('before_due','at_time','nudge')),
  offset_minutes integer,                                    -- before_due 用：提前多少分钟
  fire_at        timestamptz NOT NULL,
  sent_at        timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX reminders_due ON reminders (fire_at) WHERE sent_at IS NULL;

-- ---------- 7. 材料收集 ----------
CREATE TABLE collections (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id   text NOT NULL DEFAULT auth.uid(),
  task_id    bigint REFERENCES tasks(id) ON DELETE SET NULL,
  title      text NOT NULL,
  due_at     timestamptz,
  note       text,
  closed_at  timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE collection_targets (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id      text NOT NULL DEFAULT auth.uid(),
  collection_id bigint NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
  contact_id    bigint REFERENCES contacts(id) ON DELETE SET NULL,
  name          text NOT NULL,                               -- 冗余保存名称，联系人删了也能看
  kind          text NOT NULL DEFAULT 'department' CHECK (kind IN ('person','department','section','unit')),
  submitted_at  timestamptz,                                 -- 非空 = 已交
  note          text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------- 8. 标签库（用于自动补全） ----------
CREATE TABLE tags (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id   text NOT NULL DEFAULT auth.uid(),
  name       text NOT NULL,
  use_count  integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_id, name)
);

-- ---------- 9. 推送订阅（每台设备一行） ----------
CREATE TABLE push_subscriptions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id    text NOT NULL DEFAULT auth.uid(),
  endpoint    text NOT NULL UNIQUE,
  p256dh      text NOT NULL,
  auth        text NOT NULL,
  user_agent  text,
  last_ok_at  timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------- 10. updated_at 触发器 ----------
CREATE TRIGGER t_user_settings_touch BEFORE UPDATE ON user_settings FOR EACH ROW EXECUTE FUNCTION wb_touch_updated_at();

CREATE TRIGGER t_contacts_touch BEFORE UPDATE ON contacts FOR EACH ROW EXECUTE FUNCTION wb_touch_updated_at();

CREATE TRIGGER t_tasks_touch BEFORE UPDATE ON tasks FOR EACH ROW EXECUTE FUNCTION wb_touch_updated_at();

CREATE TRIGGER t_todos_touch BEFORE UPDATE ON todos FOR EACH ROW EXECUTE FUNCTION wb_touch_updated_at();

CREATE TRIGGER t_collections_touch BEFORE UPDATE ON collections FOR EACH ROW EXECUTE FUNCTION wb_touch_updated_at();

